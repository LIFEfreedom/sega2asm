# Обходы клеток с разрешёнными кодами: movea.l (a6,dN.w),a6 и jsr (a6) (6 байт) -> jsr заглушки.
SPAWN_SITES = [
    (0x2914E6, "2C7600004E96", 0, "обход столбца клеток: конструктор только для разрешённых кодов"),
    (0x2917FC, "2C7650004E96", 5, "обход строки клеток: конструктор только для разрешённых кодов"),
]
SPAWN_STUB = 0x200            # заглушки в SCRATCH, по 0x20 байт
SPAWN_ALLOW = 0x400           # таблица разрешённых: байт на код * 4 (как индекс в таблице обработчиков)


def spawn_stub(reg, allow):
    """movea.l 0(a6,dN.w),a6; move.l a0,-(a7); lea allow,a0; tst.b 0(a0,dN.w); movea.l (a7)+,a0;
    beq.s +2; jmp (a6); rts — movea флаги не трогает."""
    ext = "%04X" % (reg << 12)
    return bytes.fromhex("2C76" + ext + "2F08" + "41F9" + "%08X" % allow + "4A30" + ext + "205F" + "6702" + "4ED6"
                         + "4E75")


def spawn_patches(codes):
    if codes is False:
        return list(NO_OBJECTS)
    if codes is True:
        return []
    return [(at, old, "4EB9%08X" % (MegaDrive.SCRATCH + SPAWN_STUB + 0x20 * i), why)
            for i, (at, old, _, why) in enumerate(SPAWN_SITES)]


def pad_byte(buttons):
    v = 0
    for ch in buttons:
        v |= 1 << BUTTONS.index(ch)
    return v


class MegaDrive:
    """Mega Drive без картинки и звука на ядре unicorn."""

    SCRATCH = 0x00900000

    def __init__(self, rom, patches=(), spawn_codes=(), pending_vint=False):
        # pending_vint: прерывание кадра, пришедшее под маской, ждёт её снятия, как на железе (VDP держит
        # запрос до подтверждения): основной поток идёт кусками по PENDING_STEP команд, и первый же кусок
        # без маски берёт отложенное прерывание. Без флага оно теряется — так сняты трассы уровней.
        self.pending_vint = pending_vint
        self.pending = False
        self.vints = 0
        rom = bytearray(rom)
        for at, old, new, _ in patches:
            old_b, new_b = bytes.fromhex(old), bytes.fromhex(new)
            if rom[at:at + len(old_b)] != old_b:
                raise ValueError("заплатка $%06X: в ROM не %s" % (at, old))
            rom[at:at + len(new_b)] = new_b
        self.rom = bytes(rom)
        uc = self.uc = Uc(UC_ARCH_M68K, UC_MODE_BIG_ENDIAN)
        uc.ctl_set_cpu_model(M.UC_CPU_M68K_M68000)
        uc.mem_map(0, 0x400000, UC_PROT_READ | UC_PROT_EXEC)
        uc.mem_write(0, self.rom)
        self.ram = ctypes.create_string_buffer(0x10000)
        uc.mem_map_ptr(0x00FF0000, 0x10000, UC_PROT_ALL, self.ram)
        uc.mem_map_ptr(0xFFFF0000, 0x10000, UC_PROT_ALL, self.ram)
        self.z80 = bytearray(0x2000)
        # Проверка ring: байты, которые 68000 кладёт в кольцо команд драйвера $A01B40, по порядку (None — не пишем).
        self.ring = None
        self.th = 1
        self.pad = 0
        self.status = 0
        self.odd_io = {}
        uc.mmio_map(0xA00000, 0x20000, self._io_read, None, self._io_write, None)
        uc.mmio_map(0xC00000, 0x1000, self._vdp_read, None, self._vdp_write, None)
        # Регистры VDP с включения: загрузку `$297A1C` из таблицы `$297A72` (+26, 24 байта) ROM
        # пропускает — порт `$A10008` здесь читается не нулём, как при тёплом перезапуске, — а часть
        # регистров (2, 3 — адреса плоскости A и окна) игра потом не пишет.
        self.vdp = Vdp(self._bus_word, list(self.rom[VDP_INIT:VDP_INIT + 24]))
        uc.hook_add(UC_HOOK_MEM_UNMAPPED, self._unmapped)
        uc.hook_add(UC_HOOK_INTR, self._intr)
        # Запись в картридж шина пропускает: ROM её не видит, команда выполняется дальше (уровень 17: победа идола
        # портит a0 адресом $2995D0, и шаг домой пишет в ROM, $2A2DFE).
        self.rom_writes = 0
        uc.hook_add(UC_HOOK_MEM_WRITE_PROT, self._rom_write, None, 0, 0x3FFFFF)

        # Заглушки: прочитать SR процессором; войти в прерывание кадра; войти в строчное.
        vint = struct.unpack_from(">I", self.rom, VINT_VECTOR)[0]
        hint = struct.unpack_from(">I", self.rom, HINT_VECTOR)[0]
        uc.mem_map(self.SCRATCH, 0x1000, UC_PROT_ALL)
        self.stub_sr = self.SCRATCH
        self.stub_irq = self.SCRATCH + 0x20
        self.stub_hint = self.SCRATCH + 0x40
        self.sr_cell = self.SCRATCH + 0x100
        uc.mem_write(self.stub_sr, bytes.fromhex("40F9") + struct.pack(">I", self.sr_cell) + bytes.fromhex("4E71"))
        uc.mem_write(self.stub_irq, bytes.fromhex("40E7" "46FC2600" "4EF9") + struct.pack(">I", vint))
        uc.mem_write(self.stub_hint, bytes.fromhex("40E7" "46FC2400" "4EF9") + struct.pack(">I", hint))
        self.frame_sp = None
        # Строчное: стек его rte, после какой строки оно пришло, сколько раз обработчик читал статус; счётчик строк —
        # регистр 10 на конец прошлого кадра (VDP заряжает счётчик в гашении кадра, на каждой его строке).
        self.hint_sp = None
        self.hint_line = 0
        self.hint_reads = 0
        self.hint_counter = self.vdp.reg[10]
        for i, (_, _, reg, _) in enumerate(SPAWN_SITES):
            uc.mem_write(self.SCRATCH + SPAWN_STUB + 0x20 * i, spawn_stub(reg, self.SCRATCH + SPAWN_ALLOW))
        allow = bytearray(0x400)
        for code in spawn_codes or ():
            allow[code * 4] = 1
        uc.mem_write(self.SCRATCH + SPAWN_ALLOW, bytes(allow))

        ssp, pc = struct.unpack_from(">II", self.rom, 0)
        uc.reg_write(M.UC_M68K_REG_SR, 0x2700)
        uc.reg_write(M.UC_M68K_REG_A7, ssp)
        self.pc = pc
        self.fault = None

    # --- память ---

    def read(self, address, length):
        a = address & 0xFFFF
        return bytes(self.ram.raw[a:a + length])

    def word(self, address):
        return struct.unpack(">H", self.read(address, 2))[0]

    def write(self, address, data):
        a = address & 0xFFFF
        ctypes.memmove(ctypes.addressof(self.ram) + a, data, len(data))

    def _io_read(self, uc, offset, size, user):
        a = 0xA00000 + offset
        if a < 0xA04000:
            v = self.z80[offset & 0x1FFF]
            return (v << 8 | v) if size == 2 else v
        if a < 0xA04004:
            return 0
        if a in (0xA10000, 0xA10001):
            return 0xA0          # заграничная NTSC, без дисковода
        if a in (0xA10002, 0xA10003):
            p = self.pad
            if self.th:
                return 0x40 | (~p & 0x3F)
            # TH = 0: A и Start на битах 4 и 5, биты 2 и 3 — ноль (пульт на 3 кнопки)
            return ~((p & 3) | ((p >> 6) & 1) << 4 | ((p >> 7) & 1) << 5) & 0x33
        if a < 0xA10020:
            return 0x7F
        if a in (0xA11100, 0xA11101):
            return 0             # шина Z80 выдана
        self.odd_io[a] = self.odd_io.get(a, 0) + 1
        return 0

    def _io_write(self, uc, offset, size, value, user):
        a = 0xA00000 + offset
        if a < 0xA04000:
            if size == 2:
                self._z80_write(offset, (value >> 8) & 0xFF)
                self._z80_write(offset + 1, value & 0xFF)
            else:
                self._z80_write(offset, value & 0xFF)
        elif a in (0xA10002, 0xA10003):
            self.th = (value >> 6) & 1

    def _z80_write(self, offset, value):
        a = offset & 0x1FFF
        self.z80[a] = value
        if self.ring is not None and RING <= a < RING + RING_LENGTH:
            self.ring.append(value)

    def _vdp_read(self, uc, offset, size, user):
        if 4 <= offset < 8:
            # Чтение статуса сбрасывает у VDP недописанную команду (первое слово без второго).
            self.vdp.pending = False
            # Бит 3 — кадровое гашение. Внутри прерывания кадра оно идёт (очередь цветов `$2A5726`
            # сбрасывается, только увидев его); в основном потоке бит меняется на каждом чтении,
            # чтобы циклы ожидания кадра не висели.
            if self.frame_sp is not None:
                return 0x3608 if size == 2 else 0x36
            if self.hint_sp is not None:
                # Строчное: бит 2 — гашение строки. Прерывание пришло после строки N, первое чтение — уже в
                # строке N + 1, дальше гашение и строка по очереди; запись видна со строки после текущей.
                hblank = self.hint_reads & 1
                self.vdp.line = self.hint_line + 2 + (self.hint_reads >> 1)
                self.hint_reads += 1
                return (0x3604 if hblank else 0x3600) if size == 2 else 0x36
            self.status ^= 8
            return 0x3600 | self.status if size == 2 else 0x36
        if offset < 4:
            # Порт данных: VRAM, CRAM, VSRAM по команде чтения (PaletteFromCram $290BB8).
            return self.vdp.read(offset, size)
        return 0

    def _vdp_write(self, uc, offset, size, value, user):
        self.vdp.write(offset, size, value)

    def _bus_word(self, address):
        """Слово шины 68000 для DMA: ROM или ОЗУ."""
        a = address & 0xFFFFFE
        if a < len(self.rom):
            return struct.unpack_from(">H", self.rom, a)[0]
        if a >= 0xFF0000:
            return struct.unpack_from(">H", self.ram.raw, a & 0xFFFF)[0]
        return 0

    def _rom_write(self, uc, access, address, size, value, user):
        self.rom_writes += 1
        return True

    def _unmapped(self, uc, access, address, size, value, user):
        self.fault = "обращение к $%08X (вид %d) из $%08X" % (address, access, uc.reg_read(M.UC_M68K_REG_PC))
        return False

    def _intr(self, uc, intno, user):
        if intno != 0x100:
            self.fault = "исключение %d в $%08X" % (intno, uc.reg_read(M.UC_M68K_REG_PC))
            uc.emu_stop()
            return
        # rte на 68000: слово SR, длинное PC, слова формата нет
        sp = uc.reg_read(M.UC_M68K_REG_A7)
        sr, pc = struct.unpack(">HI", bytes(uc.mem_read(sp, 6)))
        uc.reg_write(M.UC_M68K_REG_A7, (sp + 6) & 0xFFFFFFFF)
        uc.reg_write(M.UC_M68K_REG_SR, sr)
        uc.reg_write(M.UC_M68K_REG_PC, pc)
        if sp == self.frame_sp:
            self.frame_sp = None
            uc.emu_stop()
        elif sp == self.hint_sp:
            self.hint_sp = None
            uc.emu_stop()

    # --- исполнение ---

    def _run(self, begin, until, count):
        try:
            self.uc.emu_start(begin, until, 0, count)
        except UcError as e:
            raise RuntimeError(self.fault or "%s в $%08X" % (e, self.uc.reg_read(M.UC_M68K_REG_PC)))
        if self.fault:
            raise RuntimeError(self.fault)

    def _sr(self):
        self._run(self.stub_sr, self.stub_sr + 6, 0)
        return struct.unpack(">H", bytes(self.uc.mem_read(self.sr_cell, 2)))[0]

    def frame(self):
        """Кусок основного потока, строчное прерывание его показа (line_interrupt_armed) и прерывание кадра, если
        маска их пускает (vints — сколько прерываний кадра взято за кадр: отложенное и своё). Записи строчного в
        VSRAM — в vdp.raster."""
        self.vints = 0
        self.vdp.raster = []
        left = BUDGET
        while self.pending and left:
            step = min(PENDING_STEP, left)
            self._run(self.pc, 0xFFFFFFFF, step)
            self.pc = self.uc.reg_read(M.UC_M68K_REG_PC)
            left -= step
            if (self._sr() >> 8) & 7 < 6:
                self.pending = False
                self._interrupt()
        if left:
            self._run(self.pc, 0xFFFFFFFF, left)
            self.pc = self.uc.reg_read(M.UC_M68K_REG_PC)
        mask = (self._sr() >> 8) & 7
        if mask < 4 and self.line_interrupt_armed():
            self._line_interrupt()
        # Счётчик строк VDP заряжает в гашении кадра из регистра 10, взято ли прерывание кадра или нет.
        if mask >= 6:
            self.pending = self.pending_vint
            self.hint_counter = self.vdp.reg[10]
            return False
        self._interrupt()
        self.hint_counter = self.vdp.reg[10]
        return True

    def line_interrupt_armed(self):
        """Пойдёт ли строчное прерывание в показе после этого кадра: разрешено (регистр 0 бит 4), счётчик строк
        кончается на экране, обработчик $FFFFE198 — из LINE_HANDLERS (маску смотрит frame)."""
        return (self.vdp.reg[0] & 0x10 and self.hint_counter < 224
                and struct.unpack(">I", self.read(LINE_HANDLER, 4))[0] in LINE_HANDLERS)

    def _interrupt(self):
        """Прерывание уровня 6 в точке self.pc основного потока: обработчик до своего rte."""
        self.vints += 1
        sp = (self.uc.reg_read(M.UC_M68K_REG_A7) - 4) & 0xFFFFFFFF
        self.uc.mem_write(sp, struct.pack(">I", self.pc))
        self.uc.reg_write(M.UC_M68K_REG_A7, sp)
        self.frame_sp = (sp - 2) & 0xFFFFFFFF
        self._run(self.stub_irq, 0xFFFFFFFF, HANDLER_LIMIT)
        if self.frame_sp is not None or self.uc.reg_read(M.UC_M68K_REG_PC) != self.pc:
            raise RuntimeError("обработчик кадра не вернулся за %d команд" % HANDLER_LIMIT)

    def _line_interrupt(self):
        """Строчное прерывание (уровень 4) в точке self.pc основного потока: пришло после строки hint_counter,
        обработчик $296976 до своего rte; его записи в VSRAM — в vdp.raster со строками, с которых они видны."""
        sp = (self.uc.reg_read(M.UC_M68K_REG_A7) - 4) & 0xFFFFFFFF
        self.uc.mem_write(sp, struct.pack(">I", self.pc))
        self.uc.reg_write(M.UC_M68K_REG_A7, sp)
        self.hint_sp = (sp - 2) & 0xFFFFFFFF
        self.hint_line = self.hint_counter
        self.hint_reads = 0
        self.vdp.line = self.hint_line + 2
        try:
            self._run(self.stub_hint, 0xFFFFFFFF, HANDLER_LIMIT)
        finally:
            self.vdp.line = None
        if self.hint_sp is not None or self.uc.reg_read(M.UC_M68K_REG_PC) != self.pc:
            raise RuntimeError("строчное прерывание не вернулось за %d команд" % HANDLER_LIMIT)


