def demo_input(rom, at):
    def buttons(stored):
        held = ~stored & 0xFF
        held = (held & ~0x30) | ((held & 0x10) << 1) | ((held & 0x20) >> 1)
        return "".join(ch for i, ch in enumerate(BUTTONS) if held >> i & 1)

    out = [(buttons(rom[at]), 1)]
    at += 2
    while rom[at]:
        out.append((buttons(rom[at]), rom[at + 1] or 256))
        at += 2
    return out


