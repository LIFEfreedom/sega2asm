def do_captions():
    u"""Титры всех сценарных экранов в PNG плюс лист различных глифов."""
    out = os.path.join(out_path("cutscene"), "captions")
    os.makedirs(out, exist_ok=True)
    seen, order = {}, []
    files = rows_tot = caps_tot = 0
    for i, a in enumerate(story_blocks()):
        d = story_block(a)
        _b, _g, _p0, _p1, txt, n = story_header(d)
        acts, _end = actors(d, 0x0C, n)
        count = sum(1 for one in acts for _o, w, _t in one
                    if w >> 12 == 2 and (w >> 8) & 0x0F == 4)
        if not count:
            continue
        caps = captions(d, txt, count)
        laid = [caption_cells(c) for c in caps]
        heights = [max((r for _c, r, _w in one), default=0) + 1
                   for one in laid]
        h = sum(x * CAP_CELL for x in heights) + CAP_GAP * (len(laid) - 1)
        w = CAP_W * CAP_CELL
        px = [bytearray([2]) * w for _ in range(h)]
        y = 0
        for one, hh in zip(laid, heights):
            for col, row, word in one:
                g = caption_glyph(word)
                if word not in seen:
                    seen[word] = g
                    order.append(word)
                blit_glyph(px, g, col * CAP_CELL, y + row * CAP_CELL, 0, 1)
            y += hh * CAP_CELL + CAP_GAP
            rows_tot += hh
        caps_tot += len(caps)
        png(os.path.join(out, "story_%03d.png" % i), w, h,
            [[CAP_PAL[v] for v in row] for row in px])
        files += 1
    cols = 32
    rows = (len(order) + cols - 1) // cols
    px = [bytearray([2]) * (cols * CAP_CELL) for _ in range(rows * CAP_CELL)]
    for k, word in enumerate(order):
        blit_glyph(px, seen[word], (k % cols) * CAP_CELL,
                   (k // cols) * CAP_CELL, 0, 1)
    sheet = os.path.join(out, "glyphs.png")
    png(sheet, cols * CAP_CELL, rows * CAP_CELL,
        [[CAP_PAL[v] for v in row] for row in px])
    with io.open(os.path.join(out, "glyphs.txt"), "w",
                 encoding="utf-8", newline="\n") as f:
        f.write(u"# Различные глифы титров, в порядке первой встречи\n")
        f.write(u"# лист glyphs.png, %d столбцов; слово = блок<<4 | глиф\n"
                % cols)
        for k, word in enumerate(order):
            f.write(u"%4d  %04X  блок %3d глиф %2d\n"
                    % (k, word, word >> 4, word & 0x0F))
    print(u"титров %d в %d файлах, строк текста %d, разных глифов %d"
          % (caps_tot, files, rows_tot, len(order)))
    print(u"лист: %s" % os.path.relpath(sheet, HERE))
    return 0


def report(f, only=None):
    p = f.write
    by_block = {}
    for c, m, k in missions():
        by_block.setdefault(k, []).append((c, m))
    ops, gaps = collections.Counter(), []
    for k in sorted(by_block):
        if only is not None and k != only:
            continue
        d = block(k)
        grec, frame, scr, txt, n = header(d)
        where = u", ".join(u"гл.%d м.%d" % cm for cm in by_block[k])
        p(u"\n## Сценка %d — %s\n\n" % (k, where))
        p(u"Блок `$%06X`, %d байт. Запись графики %d, фон %d, актёров %d.\n"
          u"Рамка окна `+$%03X`, реплики `+$%03X`.\n\n"
          % (U32(CUT_TABLE + k * 4), len(d), grec, scr, n, frame, txt))
        acts, end = actors(d, 0x0A, n)
        say = lines(d, txt)
        who = speakers(k)
        # каждому актёру его реплики по порядку: скрипт линеен, назад
        # ходит только «ждать остальных» и только на себя, так что k-е
        # слово «реплика» в скрипте — это k-й его показ при прогоне
        queue = {}
        for j, ai in enumerate(who):
            queue.setdefault(ai, []).append(j)
        for i, one in enumerate(acts):
            for _o, w, _t in one:
                ops[w >> 12] += 1
            p(u"### Актёр %d (%s) — %d команд\n\n"
              % (i, actor_brief(one), len(one)))
            p(u"```\n")
            mine = list(queue.get(i, []))
            for o, w, t in one:
                if w >> 12 == 2 and (w >> 8) & 0x0F == 1 and mine:
                    j = mine.pop(0)
                    t = u"%s %d: %s" % (t, j, u" / ".join(
                        x or u"—" for x in say[j][1]))
                p(u"+%03X  %04X  %s\n" % (o, w, t))
            p(u"```\n\n")
        if say:
            p(u"### Реплики: %d\n\n" % len(say))
            for j, (width, got) in enumerate(say):
                p(u"* %d, актёр %s, ширина %d: %s\n"
                  % (j, who[j] if j < len(who) else u"?", width,
                     u" / ".join(x or u"—" for x in got)))
            p(u"\n")
        gaps.append(frame - end)
    return ops, gaps


def main():
    args = sys.argv[1:]
    if args and args[0] == "--back":
        return do_backdrops()
    if args and args[0] == "--play":
        k = int(args[1]) if len(args) > 1 else 0
        return do_play(k)
    if args and args[0] == "--story":
        return do_story(int(args[1]) if len(args) > 1 else None)
    if args and args[0] == "--scenes":
        return do_scenes()
    if args and args[0] == "--captions":
        return do_captions()
    only = int(args[0]) if args else None

    doc = os.path.join(HERE, "docs", "game-cutscene-scripts.md")
    f = io.open(doc, "w", encoding="utf-8", newline="\n")
    f.write(u"# Скрипты сценок между миссиями\n\n")
    f.write(u"Собрано `tools/cutscene.py` (`make cutscene`).\n\n")
    f.write(u"СГЕНЕРИРОВАНО — правки затираются, меняйте инструмент.\n"
            u"Вывод, который надо сохранить, пишите в соседний, ручной "
            u"файл.\n\n")
    f.write(u"Формат блока и таблица команд разобраны в шапке "
            u"`tools/cutscene.py`.\n\n")
    f.write(u"## Какая сценка где играет\n\n")
    f.write(u"| глава | миссия | сценка |\n|---|---|---|\n")
    for c, m, k in missions():
        f.write(u"| %d | %d | %d |\n" % (c, m, k))
    ops, gaps = report(f, only)
    f.close()

    print(u"сценок: %d, разобрано блоков: %d"
          % (len(missions()), 1 if only is not None else 15))
    print(u"команд по кодам: %s"
          % u", ".join(u"%X: %d" % kv for kv in sorted(ops.items())))
    if gaps:
        print(u"хвост от конца скриптов до рамки окна: %d…%d байт"
              % (min(gaps), max(gaps)))
    print(u"сводка: %s" % os.path.relpath(doc, HERE))
    return 0


