#!/usr/bin/env python3
"""Выгрузить ВЕСЬ осмысленный текст ROM с привязкой к месту в игре.

    python tools/dumptext.py [--out docs/game-text.md]
    make dumptext

Чем отличается от `tools/findtext.py`. Тот сканирует ROM подряд и ловит
любой прогон допустимых байт, из-за чего половина улова — графика,
случайно похожая на катакану. Этот идёт от ТАБЛИЦ: находит каждую
структуру, которую читает код, и печатает её содержимое в том порядке,
в каком игра его показывает. Поэтому здесь меньше строк, но каждая
привязана к месту.

Кодировка — JIS X 0201, полуширинная катакана, один байт на символ,
терминатор `$00`. Байт `$40` переключает размер шрифта и в текст не
попадает (см. `docs/game-engine.md`).
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from unpack import unpack                                    # noqa: E402

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

KANA = "｡｢｣､･ｦｧｨｩｪｫｬｭｮｯｰｱｲｳｴｵｶｷｸｹｺｻｼｽｾｿﾀﾁﾂﾃﾄﾅﾆﾇﾈﾉﾊﾋﾌﾍﾎﾏﾐﾑﾒﾓﾔﾕﾖﾗﾘﾙﾚﾛﾜﾝﾞﾟ"
KAT = {0xA1 + i: ch for i, ch in enumerate(KANA)}

rom = open(os.path.join(HERE, "game.gen"), "rb").read()


def w(a):
    return struct.unpack(">H", rom[a:a + 2])[0]


def dec(b):
    out = []
    for x in b:
        if x == 0x40:
            continue
        elif x in KAT:
            out.append(KAT[x])
        elif 0x20 <= x < 0x7F:
            out.append(chr(x))
        else:
            out.append("{%02X}" % x)
    return "".join(out).rstrip()


def cstr(a):
    e = a
    while rom[e]:
        e += 1
    return dec(rom[a:e]), e + 1


def briefings(root, count):
    """Двухуровневая таблица: корень -> блок -> пять строк.

    Обе индексации — самоотносительные слова от начала своей таблицы.
    """
    out = []
    for i in range(count):
        blk = root + w(root + i * 2)
        n = w(blk) // 2
        lines = []
        for j in range(n):
            s, _ = cstr(blk + w(blk + j * 2))
            lines.append(s)
        out.append((blk, lines))
    return out


def records(a, end):
    """Список вида `номер, три байта, строка`: список музыки."""
    out = []
    while a < end:
        idx = rom[a]
        s, nxt = cstr(a + 4)
        out.append((idx, s))
        a = nxt
    return out


def sounds(root):
    """Звуки: таблица самоотносительных слов -> запись `номер, строка`."""
    out = []
    for i in range(w(root) // 2):
        a = root + w(root + i * 2)
        s, _ = cstr(a + 1)
        out.append((rom[a], s))
    return out


def mission_maps(chapter):
    """Номера карт из распакованного описания главы: `+$3` каждой записи."""
    _, size, d, _end = unpack(rom, chapter)
    return [d[i * 0x5C + 3] for i in range(size // 0x5C)]


def seq(a, count):
    out = []
    for _ in range(count):
        s, a = cstr(a)
        out.append(s)
    return out


def names():
    """Корневая таблица имён $049754: пять категорий."""
    root = 0x049754
    res = []
    for cat, n in ((1, 7), (2, 6), (3, 4), (4, 5), (5, 7)):
        grp = root + w(root + (cat - 1) * 2)
        res.append((cat, grp, [cstr(grp + w(grp + i * 2))[0] for i in range(n)]))
    return res


