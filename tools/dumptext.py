def main():
    out_path = os.path.join(HERE, "docs", "game-text.md")
    if "--out" in sys.argv:
        out_path = os.path.join(HERE, sys.argv[sys.argv.index("--out") + 1])

    f = open(out_path, "w", encoding="utf-8", newline="\n")
    p = f.write
    total = 0

    p("# Весь текст игры\n\n")
    p("Собрано `tools/dumptext.py` по таблицам, а не сканированием: каждая\n")
    p("строка ниже стоит там, где её читает код. Сырая выгрузка всех прогонов\n")
    p("байт — в [text.md](text.md), но половина её улова это графика.\n\n")
    p("Кодировка — JIS X 0201, полуширинная катакана, байт на символ,\n")
    p("терминатор `$00`; `$40` переключает размер шрифта и в текст не идёт.\n\n")

    p("## Где это показывают\n\n")
    p("Весь сюжетный текст игры — это **напутствие перед миссией**. Другого\n")
    p("повествования в ROM нет: ни заставок между этапами, ни реплик по ходу\n")
    p("боя. Экран рисует `ScreenAfterBattle` `$052BCE`, который получает два\n")
    p("байта состояния: `+$0` выбирает вид экрана, `+$1` — номер миссии.\n\n")
    p("```asm\n")
    p("; $006FE4\n")
    p("\tmovea.l\t(MainStatePtr).l,a6\n")
    p("\tmove.b\t$0(a6),d0         ; режим: 0 обучение, иначе кампания\n")
    p("\tmove.b\t$1(a6),d1         ; номер миссии\n")
    p("\tmove.w\td0,-(a7)\n")
    p("\tmove.w\td1,-(a7)\n")
    p("\tjsr\t(ScreenAfterBattle).l\n")
    p("```\n\n")
    p("Дальше `GfxState_056310` `$056310` вычитает из номера единицу, берёт\n")
    p("корень `$197160` (кампания) или `$1971BA` (обучение) и выводит пять\n")
    p("строк блока с шагом `$0100` по таблице имён.\n\n")
    p("Номер напутствия — **не** номер карты. Описание миссии лежит сжатым:\n")
    p("`LoadMissionState` `$006C06` берёт главу из `$060400` и распаковывает\n")
    p("её по `$5C` байт на миссию. Распаковщик разобран (см.\n")
    p("[game-compression.md](game-compression.md)), поэтому в таблице ниже\n")
    p("стоят оба числа: `+$1` — номер напутствия, `+$3` — номер записи в\n")
    p("таблице этапов `$164400`. Они расходятся почти везде.\n\n")

    p("## Напутствия перед миссией — кампания\n\n")
    p("Корень `$197160`, 45 блоков. Первая строка блока — **название\n")
    p("миссии**, остальные четыре — подсказка.\n\n")
    maps = mission_maps(0x0604D6)
    camp = briefings(0x197160, 45)
    for i, (blk, lines) in enumerate(camp):
        total += len(lines)
        p("**Миссия %d** — %s  \n" % (i + 1, lines[0] or "(без названия)"))
        p("`$%06X`, карта %d\n\n" % (blk, maps[i]))
        for s in lines[1:]:
            p("> %s  \n" % (s if s else "&nbsp;"))
        p("\n")

    p("## Напутствия перед миссией — обучение\n\n")
    p("Та же процедура берёт второй корень `$1971BA` (8 блоков), когда байт\n")
    p("`+$0` состояния равен нулю. Здесь первая строка — не название, а\n")
    p("условие победы.\n\n")
    tmaps = mission_maps(0x060424)
    tut = briefings(0x1971BA, 8)
    for i, (blk, lines) in enumerate(tut):
        total += len(lines)
        p("**Обучение %d** — `$%06X`, карта %d\n\n" % (i + 1, blk, tmaps[i]))
        for s in lines:
            p("> %s  \n" % (s if s else "&nbsp;"))
        p("\n")

    p("## Карты поединка\n\n")
    p("Семнадцать названий подряд с `$04F229`, пронумерованы в самом тексте.\n\n")
    p("| карта |\n|---|\n")
    for s in seq(0x04F229, 17):
        total += 1
        p("| %s |\n" % s.replace("|", "\\|"))
    p("\n")

    p("## Названия из игрового меню\n\n")
    p("Корневая таблица `$049754`, пять категорий (разбор в\n")
    p("[game-species.md](game-species.md)).\n\n")
    cats = {1: "погода, команда ｼｾﾞﾝ", 2: "динозавры",
            3: "растения, команда ｼｮｸﾌﾞﾂ", 4: "приказы",
            5: "цели маркировки"}
    for cat, grp, items in names():
        total += len(items)
        p("**%d. %s** — `$%06X`: %s\n\n"
          % (cat, cats[cat], grp, ", ".join(i.strip() for i in items)))

    p("## Список музыки\n\n")
    p("Записи вида «номер, три байта, строка». Это названия дорожек, они же\n")
    p("видны в звуковом тесте.\n\n")
    p("| № | название |\n|---|---|\n")
    for idx, s in records(0x04BFA2, 0x04C2F6):
        total += 1
        p("| %02X | %s |\n" % (idx, s.replace("|", "\\|")))
    p("\n")

    p("## Список звуков\n\n")
    p("Таблица самоотносительных слов `$04C2F6`, 41 запись вида\n")
    p("«номер, строка» — звукоподражания.\n\n")
    p("| № | звук |\n|---|---|\n")
    for idx, s in sounds(0x04C2F6):
        total += 1
        p("| %02X | %s |\n" % (idx, s.replace("|", "\\|")))
    p("\n")

    p("## Отдельные надписи\n\n")
    for title, rows in LOOSE:
        p("### %s\n\n" % title)
        p("| адрес | текст | где |\n|---|---|---|\n")
        for a, note in rows:
            total += 1
            s, _ = cstr(a)
            p("| `$%06X` | %s | %s |\n" % (a, s.replace("|", "\\|"), note))
        p("\n")

    p("---\n\nВсего строк в этом документе: **%d**.\n" % total)
    f.close()
    print("строк: %d" % total)
    print("записано: %s" % os.path.relpath(out_path, HERE))
    return 0


if __name__ == "__main__":
    sys.exit(main())
