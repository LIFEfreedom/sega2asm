def records():
    return [U32(LEVELS + 4 * i) for i in range(NLEV)]


def rows():
    out = []
    for i, r in enumerate(records()):
        out.append((i, r, U32(r + 0x0C), U32(r + 0x10), U32(r + 0x14),
                    U16(r + 0x34)))
    return out


def check():
    """Режим из регистра 11 против того, что делают писатели."""
    bad = []
    for i, r, h, v, _bg, r11 in rows():
        want_h = R11_H.get(r11 & 3)
        want_v = R11_V.get((r11 >> 2) & 1)
        got_h = HSCROLL.get(h, (None, "?"))[1]
        got_v = VSCROLL.get(v, (None, "?"))[1]
        if got_h != want_h or got_v != want_v:
            bad.append((i, r11, got_h, want_h, got_v, want_v))
    return bad


def drift():
    """Скорости слоёв — цепочка addi.l #imm,(a2)+ ($069A)."""
    out, a = [], DRIFT
    while ROM[a] == 0x06 and ROM[a + 1] == 0x9A:
        out.append(U32(a + 2))
        a += 6
    return out


def main():
    arg = sys.argv[1] if len(sys.argv) > 1 else ""

    if arg == "--ram":
        print("| адрес | что |")
        print("|---|---|")
        for a, t in RAM:
            print("| `%s` | %s |" % (a, t))
        return

    if arg == "--drift":
        v = drift()
        print("%d слоёв неба в loc_2A5D26, шаг накопителя 16.16:" % len(v))
        print()
        print("| № | шаг | пикселей за кадр | к предыдущему |")
        print("|---|---|---|---|")
        prev = None
        for k, x in enumerate(v):
            rel = "%.4f" % (x / float(prev)) if prev else "—"
            print("| %d | `$%08X` | %.4f | %s |" % (k, x, x / 65536.0, rel))
            prev = x
        print()
        geo = [0x30000]
        while len(geo) < len(v):
            geo.append(geo[-1] * 7 // 8)
        extra = [x for x in v if x not in geo]
        print("Ряд строго геометрический: каждый следующий ровно 7/8 от"
              " предыдущего,")
        print("от 3 пикселей за кадр и ниже — кроме одной вручную"
              " вставленной записи:")
        for x in extra:
            k = v.index(x)
            print("  №%d = `$%08X` (%.5f) — после неё №%d едет БЫСТРЕЕ"
                  " (%.5f), то есть порядок глубин раз нарушен"
                  % (k, x, x / 65536.0, k + 1, v[k + 1] / 65536.0))
        return

    bad = check()
    if arg == "--check":
        if bad:
            for i, r11, gh, wh, gv, wv in bad:
                print("уровень %d: регистр 11 = %d ждёт (%s, %s),"
                      " а пишут (%s, %s)" % (i, r11, wh, wv, gh, gv))
        else:
            print("все %d уровня: режим из регистра 11"
                  " совпадает с тем, что делают писатели" % NLEV)
        return

    print("| ур. | запись | рег. 11 | горизонталь `+$0C` |"
          " вертикаль `+$10` | фон `+$14` |")
    print("|---|---|---|---|---|---|")
    for i, r, h, v, bg, r11 in rows():
        print("| %d | `$%06X` | %d = %s / %s | `$%06X` %s | `$%06X` %s |"
              " `$%06X` %s |" % (
                  i, r, r11, R11_H.get(r11 & 3, "?"),
                  R11_V.get((r11 >> 2) & 1, "?"),
                  h, HSCROLL.get(h, ("?", ""))[0],
                  v, VSCROLL.get(v, ("?", ""))[0],
                  bg, BG.get(bg, "?")))
    print()
    if bad:
        print("СОГЛАСИЯ НЕТ в %d записях — см. --check" % len(bad))
    else:
        print("Самопроверка: режим из регистра 11 совпадает"
              " с работой писателей на всех %d из %d." % (NLEV, NLEV))


if __name__ == "__main__":
    main()
