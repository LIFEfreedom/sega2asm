class Rng(object):
    u"""`Random` `$016570`: обход таблицы-перестановки, XOR с номером круга.

    Игра ничего не подмешивает извне, так что последовательность целиком
    задана парой (индекс, круг). Настоящие их значения на момент загрузки
    карты зависят от того, сколько раз игру успели дёрнуть до того, —
    воспроизвести их нельзя, поэтому здесь берётся пара (0, 0).
    """

    def __init__(self, index=0, round_=0):
        self.i, self.r = index & 0xFF, round_ & 0xFF

    def __call__(self):
        v = ROM[RANDOM_TABLE + self.i]
        self.i = (self.i + 1) & 0xFF
        if self.i == 0:
            self.r = (self.r + 1) & 0xFF
        return v ^ self.r

    def skip(self, n):
        for _ in range(n):
            self()
        return self


def animated_mask(mrec):
    u"""`AnimatedTypeMask`, как его собирает `SeedAnimatedTiles` `$0214D2`.

    Основа `$00078FFF` — типы 0…11 и 15…18. Бит 0 байта `+$2F` миссии
    ОСТАВЛЯЕТ тип 15, бит 1 — тип 10; сброшенный бит убирает.
    """
    m = U32(ANIM_TYPE_MASK)
    if not mrec[0x2F] & 1:
        m &= ~(1 << 15)
    if not mrec[0x2F] & 2:
        m &= ~(1 << 10)
    return m & 0xFFFFFFFF


def cell_styles(cells, typeof, mask, rng=None):
    u"""Байт стиля каждой клетки, как его кладёт `SeedAnimatedTiles`.

    Стиль — четыре двухбитных кода по сторонам света: биты 6…7 верх,
    4…5 право, 2…3 низ, 0…1 лево. Ноль значит «кромки нет», код 3 —
    «нарисовать местность байтом 9», коды 1 и 2 — «нарисовать местность
    СОСЕДА», на первом или на втором месте вдоль кромки.

    Обход идёт строками, поэтому левый и верхний соседи уже посчитаны:
    их коды «право» и «низ» просто переписываются в наши «лево» и «верх».
    Случайность выбирает только 1 или 2, то есть на какое из двух мест
    ляжет заплатка; есть она вообще и какого рода — решают типы.
    """
    if rng is None:
        rng = Rng().skip(TERRAIN_CELLS)   # BuildTerrainMap идёт первым
    style = bytearray(TERRAIN_CELLS)
    types = [typeof[b] & 0x1F for b in cells]
    live = lambda t: (mask >> t) & 1

    def at(i, dx, dy):
        u"""Тип соседа; None за краем карты.

        По горизонтали индекс линейный, как в игре: у клетки в столбце 0
        «левый сосед» — это последняя клетка прошлой строки. По вертикали
        игра читает память за массивом, и что там лежит, неизвестно.
        """
        j = i + dy * W + dx
        return types[j] if 0 <= j < TERRAIN_CELLS else None

    for i in range(TERRAIN_CELLS):
        t = types[i]
        if not live(t):
            continue
        d0 = (rng() & 0x14) + 0x14        # биты 2…3 и 4…5: по 1 или 2
        n = at(i, 1, 0)                   # право
        if n == t:
            d0 &= 0xCF
        elif n is not None and not live(n):
            d0 |= 0x30
        n = at(i, 0, 1)                   # низ
        if n == t:
            d0 &= 0xF3
        elif n is not None and not live(n):
            d0 |= 0x0C
        n = at(i, -1, 0)                  # лево
        if n == t:
            d0 &= 0xFC
        elif n is None:
            pass
        elif not live(n):
            d0 |= 0x03
        else:
            d0 |= (style[i - 1] & 0x30) >> 4
        n = at(i, 0, -1)                  # верх
        if n == t:
            d0 &= 0x3F
        elif n is None:
            pass
        elif not live(n):
            d0 |= 0xC0
        else:
            d0 |= (style[i - W] & 0x0C) << 4
        style[i] = d0
    return style


def edge_slot(idx):
    u"""Какое из двух мест занимает код 3: хеш адреса клетки, `$015BAE`.

    ```asm
    	move.l	a0,d4
    	move.l	a0,d0
    	lsr.w	#1,d0
    	add.b	d0,d4
    	andi.w	#$0008,d4
    ```
    """
    a0 = MAP_BUFFER + idx * 2
    half = ((a0 & 0xFFFF) >> 1) & 0xFF
    return 1 if ((a0 + half) & 0xFF) & 8 else 0


EDGE_ADD = 0x00558A        # data_36: маска соседей -> добавка к байту


def autotile(cells):
    u"""Достройка берегов, `BuildMapEdgeCodes` `$00546E`.

    Работает, только когда взведён бит 7 байта `+$2F` описания миссии
    (93 миссии из 123), и только для байтов `$19` и `$49`: у них по восьми
    соседям собирается маска «сосед НЕ такой же», и `data_36` по ней даёт
    добавку к байту. То есть в данных лежит сплошная заливка, а кромку
    игра досчитывает при загрузке.
    """
    src = bytes(cells)
    out = bytearray(src)
    add = ROM[EDGE_ADD:EDGE_ADD + 256]
    for y in range(H):
        for x in range(W):
            i = y * W + x
            v = src[i]
            if v not in (0x19, 0x49):
                continue
            m = 0
            if y:
                if src[i - 40] != v:
                    m |= 1 << 0
                if x and src[i - 41] != v:
                    m |= 1 << 7
                if x != 39 and src[i - 39] != v:
                    m |= 1 << 1
            if y != 39:
                if src[i + 40] != v:
                    m |= 1 << 4
                if x and src[i + 39] != v:
                    m |= 1 << 5
                if x != 39 and src[i + 41] != v:
                    m |= 1 << 3
            if x and src[i - 1] != v:
                m |= 1 << 6
            if x != 39 and src[i + 1] != v:
                m |= 1 << 2
            out[i] = (v + add[m]) & 0xFF
    return bytes(out)


def placement(a):
    u"""[(x, y, направление, тип, поза)] расстановки."""
    out = []
    if not (0x100000 <= a < len(ROM) - 4):
        return out
    for _ in range(400):
        v = U16(a)
        if v & 0x8000:
            break
        out.append(((v >> 9) & 0x3F, v & 0x3F, (v >> 6) & 7,
                    ROM[a + 2], ROM[a + 3]))
        a += 4
    return out


SPECIES_BYTE = 0x01FAEE    # +$1 записи: вид плюс флаги, бит 5 — декор


def is_decor(t):
    return bool(ROM[SPECIES_BYTE + t * 4 + 1] & 0x20)


def pose_anim(t, pose, facing):
    u"""Номер анимации по байту позы; см. таблицу в шапке."""
    if pose == 0:
        return 0x0B if facing & 1 else 0x0A
    if pose == 1:
        return 0x06
    if pose in (2, 3, 7):
        return 0x05
    if pose in (4, 8):
        return 0x06 if is_decor(t) else 0x20
    return 0x0A


def unit_sprite(t, pose, facing):
    u"""32x32 номеров цветов, None вместо прозрачного; None, если кадра нет."""
    import unitgfx
    anim = pose_anim(t, pose, facing)
    try:
        words = unitgfx.walk(unitgfx.script_addr(t, anim, facing & ~1))
    except Exception:
        return None
    if not words:
        return None
    w = words[0]
    tbl = (gfx_L(unitgfx.COMMON_FRAMES) if w & 0x100
           else unitgfx.frame_table(t))
    idx = w & 0xFF
    n = table_len(tbl)
    if not n or idx >= n:
        return None
    p = gfx_L(tbl + 4 * idx)
    if not (0 < p < 0x200000):
        return None
    try:
        data = columnwise(bytes(unpack(ROM, p)[2]))
    except Exception:
        return None
    prow = (ROM[UNIT_PALETTE_ROW + t - 1] & 3) * 16
    hf = bool(w & 0x800)
    out = [[None] * 32 for _ in range(32)]
    for ty in range(4):
        for tx in range(4):
            tile = data[(ty * 4 + tx) * 32:(ty * 4 + tx + 1) * 32]
            if len(tile) < 32:
                continue
            for y in range(8):
                line = out[ty * 8 + y]
                for x in range(8):
                    b = tile[y * 4 + (x >> 1)]
                    v = (b >> 4) if x % 2 == 0 else (b & 15)
                    if not v:
                        continue
                    at = tx * 8 + x
                    line[31 - at if hf else at] = prow + v
    return out


def palettes(rec, mrec):
    u"""Четыре ряда CRAM поля боя, как их кладёт `BuildStagePalettes`."""
    return [array_palette(0), array_palette(mrec[0x28]),
            array_palette(mrec[0x29]), rec_palette(rec, mrec[0x4C])]


