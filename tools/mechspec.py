def meta():
    return {
        "game": "Maui Mallard in Cold Shadow (Mega Drive)",
        "rom_sha1": hashlib.sha1(bytes(SJ.ROM)).hexdigest().upper(),
        "generator": "tools/mechspec.py",
        "spec": "docs/mauimallard/mechanisms.md",
        "values": u"операнды команд как в коде: перезарядка n при "
                  u"subq/bpl — событие через n + 1 кадров; _bcd — "
                  u"двоично-десятичное; скорость 8.8; _px — точки",
    }


def main():
    try:
        tree = SJ.from_entries(ROWS)
    except SJ.SpecError as e:
        print(u"ошибка: %s" % e)
        return 1
    if SJ.ERRORS:
        for e in SJ.ERRORS:
            print(u"ошибка: %s" % e)
        print(u"ошибок: %d" % len(SJ.ERRORS))
        return 1
    vals, srcs = SJ.split(tree)
    n = SJ.count(tree)
    if "--check" in sys.argv:
        print(u"проверено чисел: %d" % n)
        return 0
    out = OUT("export")
    if not os.path.isdir(out):
        os.makedirs(out)
    doc = dict(meta=meta(), **vals)
    for name, data in (("mechanisms.json", doc),
                       ("mechanisms.sources.json", srcs)):
        p = os.path.join(out, name)
        with io.open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(json.dumps(data, ensure_ascii=False, indent=1))
        print(p)
    print(u"чисел: %d" % n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
