#!/usr/bin/env python3
"""Нотная строка звукового драйвера: разбор одного формата на двоих.

Песни (`music.py`) и звуковые эффекты (`sfx.py`) читаются одним и тем же
интерпретатором — отличается только источник байт. Поэтому таблица команд
и обход строки живут здесь, а не в двух копиях.

Байт строки:

| байт | что |
|---|---|
| `$00`–`$7F` | пауза; длительность = байт × множитель |
| `$80` | снять ноту |
| `$81`–`$DF` | нота: номер в таблице частот плюс транспонирование |
| `$E0`–`$FF` | команда, таблица `$0ADB` |

**Сколько у команды операндов — вычитано из обработчиков, а не угадано.**
Диспетчер `$0ACB` входит в обработчик с `de` на первом операнде и `a`,
равным этому байту, а после возврата делает `inc de`. Значит обработчик,
который не трогает `de`, съедает ровно один байт; каждый лишний `inc de`
внутри — ещё один операнд. По этому признаку сосчитаны все тридцать две
команды, и пять из них разошлись с прежним разбором: `$F0` берёт четыре
байта (`$0C3B`), `$F1` — два (`$0C49`), `$F7` — четыре (`$0D1D`),
`$EB` — три (`$0BBD`), а `$FE` — четыре, а не восемь (`$0D90` и ветка
пропуска `$0DC3`).
"""

# Имя команды и число байт операнда. Там, где число зависит от операнда,
# стоит None и работает nops().
CMD = {
    0xE0: ("панорама", 1),
    0xE1: ("поле +16", 1),
    0xE2: ("($1C16)", 1),
    0xE3: ("заглушить и кончить", 1),
    0xE4: ("копия пяти байт", 5),
    0xE5: ("громкость дважды", 2),
    0xE6: ("громкость", 1),
    0xE7: ("флаг 1", 0),
    0xE8: ("держать", 1),
    0xE9: ("LFO и панорама", 2),
    0xEA: ("СЭМПЛ DAC", 1),
    0xEB: ("счётчик, на нуле переход", 3),
    0xEC: ("громкость PSG", 1),
    0xED: ("регистр YM I", 2),
    0xEE: ("регистр YM II", 2),
    0xEF: ("ИНСТРУМЕНТ", None),
    0xF0: ("огибающая", 4),
    0xF1: ("поле +7 (два байта)", 2),
    0xF2: ("КОНЕЦ", 0),
    0xF3: ("шум PSG", 1),
    0xF4: ("поле +7", 1),
    0xF5: ("PSG +8", 1),
    0xF6: ("ПЕРЕХОД", 2),
    0xF7: ("ЦИКЛ", 4),
    0xF8: ("ВЫЗОВ", 2),
    0xF9: ("ВОЗВРАТ", 0),
    0xFA: ("поле +2", 1),
    0xFB: ("транспонирование", 1),
    0xFC: ("флаг 5", 1),
    0xFD: ("флаг 3", 1),
    0xFE: ("частоты операторов", 4),
    0xFF: ("расширение", None),
}

# Подкоманды `$FF`: имя и сколько байт СВЕРХ самого номера подкоманды.
SUB = {
    0x00: ("темп", 1),
    0x01: ("команда драйвера", 1),
    0x02: ("($1C11), снять музыку", 1),
    0x03: ("блочная запись", None),
    0x04: ("поле +2 всем слотам", 1),
    0x05: ("четыре регистра SSG-EG", 4),
    0x06: ("как у канала-эффекта", 1),
}

END = (0xF2, 0xE3)


def nops(rd, at):
    """Сколько байт занимает операнд команды по адресу at."""
    code = rd(at)
    name, n = CMD.get(code, ("?", 1))
    if n is not None:
        return n
    if code == 0xEF:
        # Отрицательный номер — второй байт: номер песни, откуда патч
        # (`$0C0F`: jp p, иначе inc de и ещё один ld a,(de)).
        return 2 if rd(at + 1) >= 0x80 else 1
    if code == 0xFF:
        sub = rd(at + 1)
        _s, k = SUB.get(sub, ("?", 1))
        if k is not None:
            return 1 + k
        # $FF $03 aa bb cc + cc байт данных: ldir гонит их из самой строки.
        return 1 + 3 + rd(at + 4)
    return 1


def text(rd, at):
    """Команда в читаемом виде: имя, код и байты операнда."""
    code = rd(at)
    n = nops(rd, at)
    name = CMD.get(code, ("?", 1))[0]
    if code == 0xFF:
        name = "%s/%s" % (name, SUB.get(rd(at + 1), ("?",))[0])
    ops = " ".join("$%02X" % rd(at + 1 + k) for k in range(n))
    return "%s $%02X" % (name, code), ops


def walk(rd, start, mul=1, limit=4000):
    """Строка в события: (адрес, что, аргумент, длительность в тиках).

    Переход `$F6` прослеживается, `$F8`/`$F9` — тоже. Повторный заход в
    уже пройденный адрес кончает обход пометкой «по кругу», но **вызов**
    разобранной подпрограммы обход не рвёт: её просто не перечитывают, а
    идут дальше за вызовом. `$F7` и `$EB` ветвятся по счётчику в слоте,
    поэтому берётся ветка проваливания — иначе конца не будет.
    """
    out = []
    a = start
    seen = set()
    stack = []
    dur = 0
    while len(out) < limit:
        if a in seen:
            out.append((a, "…дальше по кругу", None, 0))
            break
        seen.add(a)
        b = rd(a)
        at = a
        if b >= 0xE0:
            n = nops(rd, a)
            what, ops = text(rd, a)
            a += 1 + n
            if b == 0xF8:
                tgt = rd(at + 1) | (rd(at + 2) << 8)
                if tgt in seen:
                    # Ту же подпрограмму зовут не раз; перечитывать её
                    # незачем, но и обход из-за этого кончать не надо.
                    ops += "  (уже разобрана)"
                else:
                    stack.append(a)
                    a = tgt
            elif b == 0xF9:
                if not stack:
                    out.append((at, what, ops, 0))
                    break
                a = stack.pop()
            elif b == 0xF6:
                a = rd(at + 1) | (rd(at + 2) << 8)
            out.append((at, what, ops, 0))
            if b in END:
                break
            continue
        a += 1
        if b < 0x80:
            out.append((at, "пауза", "%d" % (b * mul), b * mul))
            continue
        if b == 0x80:
            out.append((at, "снять", None, 0))
            continue
        nxt = rd(a)
        if nxt < 0x80:
            a += 1
            dur = nxt * mul
            arg = "%d" % dur
        else:
            arg = "как раньше"
        out.append((at, "нота №%d" % (b - 0x81), arg, dur))
    return out


def ticks(events):
    """Сколько тиков занимает строка до конца или до первой петли."""
    return sum(e[3] for e in events)
