def _check(sites, described):
    bad = []
    for a in sorted(set(sites) - set(described)):
        bad.append(u"нет описания: %s" % hexa(a))
    for a in sorted(set(described) - set(sites)):
        bad.append(u"описано, но в ROM нет: %s" % hexa(a))
    dup = [a for a in described if described.count(a) > 1]
    for a in sorted(set(dup)):
        bad.append(u"описано дважды: %s" % hexa(a))
    return bad


def census():
    """-> (события, все места {адрес: (вид, V)}), с проверкой полноты."""
    code = code_sites()
    scr = script_sites()
    for a in COMPUTED_ENTRIES:
        seen = set()
        _reach(a, seen)
        for p in seen:
            if ROM[p] in (0xEA, 0xEB) and p not in scr:
                scr[p] = ("start" if ROM[p] == 0xEA else "stop",
                          SJ.cmd(p, [ROM[p]], signed=False, size=1))
    sites = dict(code)
    sites.update(scr)
    described = [a for ev in EVENTS for a in ev[3]] + list(DYNAMIC)
    bad = _check(list(sites), described)
    for a in DYNAMIC:
        if a in code and code[a][1] is not None:
            bad.append(u"%s: номер в pea, а описан как вычисляемый" % hexa(a))
    for ev in EVENTS:
        for a in ev[3]:
            if a in code and code[a][1] is None:
                bad.append(u"%s: номер вычисляется — место для DYNAMIC"
                           % hexa(a))
    for b in bad:
        SJ.ERRORS.append(b)
    out = []
    for dom, who, what, adrs in EVENTS:
        kinds = set(sites[a][0] for a in adrs if a in sites)
        nums = []
        for a in adrs:
            if a in sites and sites[a][1] is not None:
                nums.append(sites[a][1])
        uniq = OrderedDict()
        for v in nums:
            uniq.setdefault(v.v, v)
        out.append(OrderedDict([
            ("domain", dom), ("who", who), ("event", what),
            ("action", "stop" if kinds == {"stop"} else "start"),
            ("sounds", list(uniq.values())),
            ("via", sorted(set(u"скрипт" if a in scr else u"код"
                               for a in adrs))),
            ("sites", [hexa(a) for a in adrs])]))
    for a, f in DYNAMIC.items():
        got = f()
        dom, who, what, vals = got[:4]
        uniq = OrderedDict()
        for v in vals:
            uniq.setdefault(v.v, v)
        rec = OrderedDict([
            ("domain", dom), ("who", who), ("event", what),
            ("action", "start"), ("sounds", list(uniq.values())),
            ("via", [u"код, номер вычисляется"]), ("sites", [hexa(a)])])
        if len(got) > 4:
            rec.update(got[4])
        out.append(rec)
    order = list(DOMAINS)
    out.sort(key=lambda e: order.index(e["domain"]))
    return out, sites


def catalog(events):
    used = defaultdict(list)
    for i, e in enumerate(events):
        for v in e["sounds"]:
            used[v.v].append(i)
    launched = defaultdict(list)
    profiles = [sound_profile(n) for n in range(Z.sound_count())]
    for n, p in enumerate(profiles):
        for m in p["launches"]:
            launched[m].append(n)
    heard = set(used)
    grew = True
    while grew:
        grew = False
        for n, p in enumerate(profiles):
            if n in heard:
                for m in p["launches"]:
                    if m not in heard:
                        heard.add(m)
                        grew = True
    music_of = {}
    for name, chain, _where in MUSIC:
        for n in chain:
            music_of.setdefault(n, name)
    out = []
    for n, p in enumerate(profiles):
        w = _wav(n)
        if p["tracks"].v == 0:
            kind = "empty"
        elif n in music_of:
            kind = "music"
        elif p["loop"]:
            kind = "loop"
        else:
            kind = "sfx"
        rec = OrderedDict([("n", n), ("hex", "$%02X" % n), ("kind", kind)])
        rec.update(p)
        rec["music"] = music_of.get(n)
        rec["launched_by"] = launched.get(n, [])
        rec["events"] = used.get(n, [])
        rec["heard"] = n in heard
        if w:
            sub, sec, total = w
            rec["wav"] = "sound/%s/sound_%03d.wav" % (sub, n)
            rec["seconds"] = (u"%.2f" % sec if kind in ("sfx",) or
                              sec < total - 0.05 else None)
        else:
            rec["wav"], rec["seconds"] = None, None
        out.append(rec)
    return out


