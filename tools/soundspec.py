def sites_report(sites):
    for a in sorted(sites):
        kind, v = sites[a]
        src = u"скрипт" if SCRIPTS[0] <= a < SCRIPTS[1] else u"код"
        print(u"%s  %-5s %-6s %s" % (hexa(a), kind, src,
                                     "$%02X" % v.v if v else u"вычисл."))
    print(u"мест: %d" % len(sites))


def table(tree):
    ev = tree["events"]
    for s in tree["sounds"]:
        who = u"; ".join(u"%s — %s" % (ev[i]["who"], ev[i]["event"])
                         for i in s["events"])
        print(u"%3d %s %-5s tr%-2d %-6s %s" % (
            s["n"], s["hex"], s["kind"], s["tracks"], s["seconds"] or u"",
            who[:150]))


