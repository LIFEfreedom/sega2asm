E = SJ.E
ROM = SJ.ROM
U32 = lambda a: struct.unpack_from(">I", ROM, a)[0]          # noqa: E731
S16 = lambda a: struct.unpack_from(">h", ROM, a)[0]          # noqa: E731

START, STOP = 0x2F8DCC, 0x2F8DEA
SCRIPTS = A.SCRIPTS
# Вызовы внутри обработчиков команд скрипта $EA/$EB — механизм, не событие.
SCRIPT_HANDLERS = {0x29723A: "$EA", 0x29725C: "$EB"}


# ------------------------------------------------------------ перепись

PEA = re.compile(r"^pea \((\$[0-9A-F]+|header)\)\.w$")


def _pea(a):
    """Номер из `pea` прямо перед вызовом -> V или None."""
    i = E.ADDRS.index(a)
    p = E.ADDRS[i - 1]
    m = PEA.match(E.BY[p])
    if not m:
        return None
    g = m.group(1)
    v = 0 if g == "header" else int(g[1:], 16)
    return V(v, "%s: pea ($%06X).w" % (hexa(p), v))


def code_sites():
    """{адрес вызова: (START|STOP, V номера или None)}."""
    out = {}
    for tgt, kind in ((START, "start"), (STOP, "stop")):
        pat = b"\x4e\xb9" + struct.pack(">I", tgt)
        i = ROM.find(pat)
        while i >= 0:
            if i in E.BY and i not in SCRIPT_HANDLERS:
                out[i] = (kind, _pea(i))
            i = ROM.find(pat, i + 1)
    return out


def script_entries():
    """Адреса скриптов, которые где-то называются: код и данные."""
    lo, hi = SCRIPTS
    refs = set()
    rx = re.compile(r"(?:#\$00|\(\$)(1D[0-9A-F]{4})\b")
    for a in E.ADDRS:
        for m in rx.finditer(E.BY[a]):
            v = int(m.group(1), 16)
            if lo <= v < hi and v % 2 == 0:
                refs.add(v)
    for a in range(0x1D0000, 0x200000, 2):
        if lo <= a < hi:
            continue
        v = U32(a)
        if lo <= v < hi and v % 2 == 0:
            refs.add(v)
    return refs


def _reach(start, seen):
    lo, hi = SCRIPTS
    todo = [start]
    while todo:
        a = todo.pop()
        while lo <= a < hi and a not in seen:
            seen.add(a)
            op = ROM[a]
            if op < 0xD8:
                a += 2
                continue
            if op == 0xD9:                      # цель — от самой команды
                a += S16(a + 2)
                continue
            if op in (0xDB, 0xE5):              # от конца слова команды
                todo.append(a + 2 + S16(a + 2))
            elif op == 0xE6:
                todo.append(a + 4 + S16(a + 4))
            a += A.CMDS.get(op, (2, ""))[0]


def script_sites():
    """{позиция команды: (START|STOP, V номера)} на достижимых путях."""
    seen = set()
    for s in script_entries():
        _reach(s, seen)
    out = {}
    for a in sorted(seen):
        if ROM[a] in (0xEA, 0xEB):
            kind = "start" if ROM[a] == 0xEA else "stop"
            out[a] = (kind, SJ.cmd(a, [ROM[a]], signed=False, size=1))
    return out


# ------------------------------------------------------------ звуки

WAV = os.path.join(OUT("sound"))


def _wav(n):
    """(каталог, секунды слышимого) по выгрузке z80render, либо None."""
    for sub in ("sfx", "music"):
        p = os.path.join(WAV, sub, "sound_%03d.wav" % n)
        if not os.path.exists(p):
            continue
        w = wave.open(p)
        ch, fr, cnt = w.getnchannels(), w.getframerate(), w.getnframes()
        data = w.readframes(cnt)
        last = 0
        for i in range(len(data) // 2 - 1, -1, -1):
            if abs(struct.unpack_from("<h", data, i * 2)[0]) > 200:
                last = i // ch
                break
        return sub, last / float(fr), cnt / float(fr)
    return None


def _track(a):
    info = {"voices": set(), "launch": set(), "loop": False, "back": False,
            "stop": set(), "set": set(), "test": set()}
    for _ in range(8000):
        op = ROM[a]
        if op < 0x60:
            a += 1
            continue
        if op < 0x73:
            n = Z.CMD[op][1]
            arg = ROM[a + 1:a + 1 + n]
            if op == 0x61:
                info["voices"].add(Z.voice_kind(arg[0]))
            elif op == 0x6B:
                info["launch"].add(arg[0])
            elif op == 0x64 and arg[0] == 0x7F:
                info["loop"] = True
            elif op == 0x6F and (arg[0] | arg[1] << 8) >= 0x8000:
                info["back"] = True
            elif op == 0x72 and arg[0] == 0:
                info["stop"].add(arg[1])
            elif op == 0x70:
                info["set"].add(arg[0])
            elif op == 0x71:
                info["test"].add(arg[0])
            a += 1 + n + (1 if op == 0x71 else 0)
            if op == 0x60:
                break
            continue
        if op < 0x80:
            a += 1
            continue
        a = Z.number(a, op & 0xC0)[1]
    return info


PAL_PARAM = 0x15


def sound_profile(n):
    d, cnt, addrs = Z.tracks(n)
    tr = [_track(a) for a in addrs]
    u = lambda k: sorted(set().union(*[t[k] for t in tr])) if tr else []
    voices = u("voices")
    launch = u("launch")
    stops = [s for s in u("stop") if s != n]
    guard = [p for p in u("test") if p != PAL_PARAM]
    return OrderedDict([
        ("tracks", db(d)),
        ("voices", [{"FM": "FM", u"ударные": "samples", "PSG": "PSG",
                     "PSG-2": "PSG"}.get(v, v) for v in voices]),
        ("loop", any(t["loop"] for t in tr)),
        ("jumps_back", any(t["back"] for t in tr)),
        ("launches", launch),
        ("stops", stops),
        ("guard_params", guard),
        ("sets_params", [p for p in u("set") if p != PAL_PARAM]),
        ("pal_tempo", PAL_PARAM in u("test")),
    ])


