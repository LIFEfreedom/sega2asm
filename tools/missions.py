#!/usr/bin/env python3
"""Разобрать описания миссий: 92 байта на миссию, семь глав.

    python tools/missions.py            # сводка по всем главам
    python tools/missions.py --out docs/game-missions.md
    make missions

Главы лежат сжатыми, указатели в `ChapterTable` = `$060400`; распаковка —
`tools/unpack.py`. Раскладка записи выведена из кода, который её читает;
что чем оказалось — в шапке готового документа.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from unpack import unpack                                    # noqa: E402

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

rom = open(os.path.join(HERE, "game.gen"), "rb").read()
REC = 0x5C

COMMANDS = ["ｼｾﾞﾝ природа", "ﾀﾏｺﾞ яйцо", "ｼｮｸﾌﾞﾂ растения", "ｼﾚｲ приказы",
            "ｷｬｯﾁ", "ｶｲｿﾞｳ переделка", "ﾕｳﾄﾞｳ наведение",
            "ﾏｰｷﾝｸﾞ маркировка"]

ORDERS = {8: "ｼﾝｹﾞｷ", 9: "ﾊﾝｼｮｸ", 0x0A: "ｼｭｳｺﾞｳ", 0x0B: "ﾄﾂｹﾞｷ",
          0x0C: "ﾗﾝﾄｳ"}


def chapters():
    out = []
    for c in range(9):
        p = struct.unpack(">I", rom[0x060400 + c * 4:0x060404 + c * 4])[0]
        if not (0 < p < 0x280000):
            continue
        method, size, d, _end = unpack(rom, p)
        out.append((c, p, method, [d[i * REC:(i + 1) * REC]
                                   for i in range(size // REC)]))
    return out


def species(t):
    return rom[0x01FAEE + t * 4 + 1] & 0x1F


def stage_types(mp):
    """Какие типы стоят на этапе по его сценарию расстановки."""
    p = struct.unpack(">I", rom[0x164400 + (mp - 1) * 8 + 4:
                                0x164400 + (mp - 1) * 8 + 8])[0]
    out, a = set(), p
    while struct.unpack(">h", rom[a:a + 2])[0] >= 0:
        out.add(rom[a + 2])
        a += 4
    return out


def bcd(b):
    return "".join("%02X" % x for x in b).lstrip("0") or "0"


def briefing_name(mode, n):
    """Первая строка блока напутствия — название миссии."""
    root = 0x1971BA if mode == 0 else 0x197160

    def w(a):
        return struct.unpack(">H", rom[a:a + 2])[0]

    blk = root + w(root + (n - 1) * 2)
    a = blk + w(blk)
    e = a
    while rom[e]:
        e += 1
    kana = ("｡｢｣､･ｦｧｨｩｪｫｬｭｮｯｰｱｲｳｴｵｶｷｸｹｺｻｼｽｾｿﾀﾁﾂﾃﾄﾅﾆﾇﾈﾉﾊﾋﾌﾍﾎﾏﾐﾑﾒﾓ"
            "ﾔﾕﾖﾗﾘﾙﾚﾛﾜﾝﾞﾟ")
    kat = {0xA1 + i: ch for i, ch in enumerate(kana)}
    s = "".join(kat.get(x, chr(x) if 0x20 <= x < 0x7F else "")
                for x in rom[a:e] if x != 0x40)
    return s.strip()


def main():
    out_path = os.path.join(HERE, "docs", "game-missions.md")
    if "--out" in sys.argv:
        out_path = os.path.join(HERE, sys.argv[sys.argv.index("--out") + 1])
    f = open(out_path, "w", encoding="utf-8", newline="\n")
    p = f.write

    p("# Описание миссии: все 92 байта\n\n")
    p("Собрано `tools/missions.py`. Записи лежат сжатыми в главах, на\n")
    p("которые указывает `ChapterTable` `$060400`; распаковщик разобран в\n")
    p("[game-compression.md](game-compression.md). `LoadMissionState`\n")
    p("`$006C06` копирует `$5C` байт выбранной записи в `MainState`\n")
    p("`$FF028A`, и дальше игра читает поля оттуда через `MainStatePtr`.\n\n")

    p("## Раскладка\n\n")
    p("| смещение | размер | что | откуда известно |\n|---|---|---|---|\n")
    rows = [
        ("+$00", 1, "режим, он же номер главы",
         "`$05353E` сравнивает с 2, `$0553C2` с 8; селектор напутствий "
         "проверяет на ноль"),
        ("+$01", 1, "номер напутствия",
         "`DrawMissionBrief` `$056310` вычитает единицу и индексирует "
         "`$197160`"),
        ("+$02", 1, "`$FF` у последней миссии главы",
         "`$0039C0`: `bpl` мимо разбора конца главы"),
        ("+$03", 1, "номер этапа в `$164400`", "`$006C5E`"),
        ("+$04…+$0D", 10, "**типы юнитов игрока 1**",
         "по умолчанию 5…14 — ровно типы первого игрока"),
        ("+$0E…+$17", 10, "**типы юнитов игрока 2**",
         "по умолчанию 15…24 — типы второго"),
        ("+$18…+$27", 16, "**список типов нейтральных существ** с нулевым "
         "хвостом", "читателя НЕТ — см. ниже"),
        ("+$28, +$29", 2, "номера палитр",
         "`$0053A6` → `loc_006B2C`: `data_99` по 32 байта"),
        ("+$2A", 1, "набор графики этапа",
         "`$0053E4` → `CoreUnpack_006B3C`, запись `$1CC` байт в `$FF02E6`"),
        ("+$2C", 1, "номер сценки",
         "`$003B7C` → `loc_006BB0`: таблица переходов из `$00E46E`"),
        ("+$2D", 1, "процедура ПОСЛЕ боя",
         "`$004BCE` → `loc_006B9C`, `data_88`; в кампании всегда 0"),
        ("+$2E", 1, "процедура ДО боя", "`$0039AC` → тот же `data_88`"),
        ("+$2F", 1, "два бита правил",
         "`$0214EC`: бит 0 и бит 1 гасят биты 15 и 10 маски `$FFE060`"),
        ("+$30", 1, "**номер музыки**", "`$003B0C` → трап `$FF30`"),
        ("+$32, +$33", 2, "**начальный приказ игроков 1 и 2**",
         "`$0164D2`: прямо в `+$F` состояния игрока"),
        ("+$34…+$37", 4, "**деньги игрока 1**, BCD",
         "`$0164DE` в `+$2` состояния; `CanAfford` сравнивает цену с `+$2`"),
        ("+$38…+$3B", 4, "**деньги игрока 2**, BCD", "`$0164E4`"),
        ("+$3C…+$4B", 16, "**восемь слов: какие подкоманды разрешены**",
         "`$024E7C`: слово по номеру команды, девять бит — девять "
         "подпунктов"),
        ("+$4C", 1, "палитра внутри записи этапа",
         "`$0053C2`: `$FF02E6 + d0 × 32`"),
        ("+$4D, +$4E", 2, "ещё две палитры", "`$03F23A`, `$03F200`"),
        ("+$4F…+$5B", 13, "всегда ноль", "—"),
    ]
    for off, n, what, src in rows:
        p("| `%s` | %d | %s | %s |\n" % (off, n, what, src))
    p("\n")

    p("## Разрешённые команды\n\n")
    p("Самое содержательное поле. Когда игрок открывает команду, её номер\n")
    p("лежит в `$FF9C72`, и `$024E62` берёт слово по этому номеру:\n\n")
    p("```asm\n")
    p("\tmove.b\t($FF9C72).l,d0\n")
    p("\tbeq.w\t<выход>\n")
    p("\tsubq.b\t#1,d0\n")
    p("\tadd.b\td0,d0\n")
    p("\tmovea.l\t(MainStatePtr).l,a0\n")
    p("\tmove.w\t($3C,a0,d0.w),d1\n")
    p("\tlea\t($FF9C7B).l,a0\n")
    p("\tmoveq\t#8,d2\n")
    p("loc_024E88:\n")
    p("\tbtst\td2,d1\n")
    p("\tbne.w\tloc_024E90\n")
    p("\tst\t(a0)              ; бит сброшен — пункт недоступен\n")
    p("loc_024E90:\n")
    p("\tsubq.l\t#1,a0\n")
    p("\tdbf\td2,loc_024E88\n")
    p("```\n\n")
    p("Девять байт `$FF9C73`…`$FF9C7B` — по одному на подпункт; отрисовка\n")
    p("меню (`$005942`) пропускает те, что стали отрицательными. Значит\n")
    p("**взведённый бит = пункт доступен**, и бит `n` отвечает за подпункт\n")
    p("`n + 1`. Слова идут в порядке верхнего меню:\n\n")
    p("| слово | смещение | команда |\n|---|---|---|\n")
    for i, name in enumerate(COMMANDS):
        p("| %d | `+$%02X` | %s |\n" % (i, 0x3C + i * 2, name))
    p("\nПроверка: у миссий 1…4 слово приказов равно нулю, а первое\n")
    p("напутствие, где вообще упоминаются ﾊﾝｼｮｸ и ｼﾝｹﾞｷ, — пятое.\n\n")

    p("## Шестнадцать байт на `+$18`\n\n")
    p("Поле непустое у семнадцати миссий кампании из сорока пяти, у двух\n")
    p("миссий второй главы и у одной восьмой; в обучении и в главах 3, 4, 5\n")
    p("оно нулевое везде. Заполняются первые один-три байта, дальше нули.\n\n")
    p("Все значения без исключения — **номера типов юнитов, и все из\n")
    p("нейтрального пула**: 50, 51, 52 (виды 11, 12, 13), 55 (вид 16),\n")
    p("56 (вид 18), 58 (вид 20), 64 и 65 (вид 19), 68 (вид 25). Ни одного\n")
    p("типа игроков и ни одного значения вне таблицы типов.\n\n")
    p("| миссия | этап | список | стоит на своём этапе? |\n|---|---|---|---|\n")
    for c, base, method, recs in chapters():
        if c != 1:
            continue
        for i, r in enumerate(recs):
            lst = [x for x in r[0x18:0x28] if x]
            if not lst:
                continue
            on = stage_types(r[3])
            ok = [t for t in lst if t in on]
            p("| %d | %d | %s | %s |\n"
              % (i + 1, r[3],
                 ", ".join("%d (вид %d)" % (t, species(t)) for t in lst),
                 ", ".join(map(str, ok)) if ok else "**нет**"))
    p("\nВ тринадцати случаях из семнадцати названный тип действительно\n")
    p("стоит на этапе этой же миссии: у миссии 45 это все три части\n")
    p("ﾒｶﾞｻﾞｳﾙｽ, у миссии 44 — носитель вида 16, у миссии 4 — пустые яйца.\n")
    p("В четырёх (9, 20, 37, 38) не стоит.\n\n")
    p("**И при этом поле никто не читает.** Проверено так: собраны все\n")
    p("процедуры, где `MainStatePtr` попадает в адресный регистр, и в них\n")
    p("проверено каждое обращение со смещением `$18`…`$27` по этому\n")
    p("регистру — семь находок, все до одной по другим базам (`$24E8(a5)`,\n")
    p("`$3DA6(a5)`). Обращений по абсолютному адресу `$FF02A2`…`$FF02B1`\n")
    p("в ROM нет ни одного. Указатель внутрь записи строится ровно дважды:\n")
    p("`lea $28(a6),a1` для палитр и `lea $3C(a1),a1` в отладочной\n")
    p("разблокировке команд — ни один не попадает в этот участок.\n\n")
    p("Значит поле заполнено осмысленно, но в этой сборке мертво. Такие\n")
    p("следы в игре не в новинку: маска нарезки по кадрам в главном цикле\n")
    p("обнулена, у шести действий обработчик из трёх `nop`, а у\n")
    p("`RuleMorphPlayer2` первая ветка недостижима.\n\n")
    p("Оговорка: разбор идёт по потоку, и код, до которого добираются\n")
    p("только через указатель, анализатор пропускает. «Читателя нет» —\n")
    p("утверждение слабее, чем «читатель найден», и держится ровно на\n")
    p("перечисленном выше.\n\n")

    p("## Кампания, все 45 миссий\n\n")
    p("| № | название | этап | деньги P1 | P2 | музыка | до/после | ")
    p("ｼｾﾞﾝ | ﾀﾏｺﾞ | ｼｮｸﾌﾞﾂ | ｼﾚｲ | ｷｬｯﾁ | ｶｲｿﾞｳ | ﾕｳﾄﾞｳ | ﾏｰｸ |\n")
    p("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
    for c, base, method, recs in chapters():
        if c != 1:
            continue
        for i, r in enumerate(recs):
            ws = [struct.unpack(">H", r[0x3C + k * 2:0x3E + k * 2])[0]
                  for k in range(8)]
            p("| %d | %s | %d | %s | %s | %d | %d/%d | %s |\n"
              % (i + 1, briefing_name(1, r[1]), r[3],
                 bcd(r[0x34:0x38]), bcd(r[0x38:0x3C]), r[0x30],
                 r[0x2E], r[0x2D],
                 " | ".join("%04X" % x for x in ws)))
    p("\n")

    p("## Главы\n\n")
    p("| глава | адрес | метод | миссий | этапы |\n|---|---|---|---|---|\n")
    for c, base, method, recs in chapters():
        mp = [r[3] for r in recs]
        p("| %d | `$%06X` | %d | %d | %d…%d |\n"
          % (c, base, method, len(recs), min(mp), max(mp)))
    p("\nГлавы 6 и 7 — нулевые указатели.\n")

    p("\n## Чего я НЕ установил\n\n")
    p("- Зачем записи список нейтральных типов, если его никто не читает:\n")
    p("  вырезанная возможность или задел — по коду не различить.\n")
    p("- Что означают биты 0 и 1 поля `+$2F` и маска `$FFE060`.\n")
    p("- Нумерацию подпунктов внутри каждой команды сверял только для\n")
    p("  приказов; для остальных порядок взят из меню.\n")
    f.close()
    print("записано: %s" % os.path.relpath(out_path, HERE))
    return 0


if __name__ == "__main__":
    sys.exit(main())
