#!/usr/bin/env python3
"""Чего стоит шаг: скорость и урон от местности по видам.

    make terrain

В блоке параметров вида три таблицы, проиндексированные типом местности:

| таблица | смещение | размер | что |
|---|---|---|---|
| A | `+$3A` | 22 байта | делитель скорости шага |
| B | `+$50` | 22 слова | урон, пока юнит идёт или оглушён |
| C | `+$7C` | 22 слова | урон при входе в следующую клетку |

У улучшенного юнита те же три подряд с `+$D8`, `+$EE` и `+$11A`; выбор по
биту 5 байта `+$11` записи юнита.

**Усталости как отдельной шкалы в игре нет.** Таблица A здоровья не тратит
вовсе: её значение ложится в `+$1F` и работает делителем. Накопитель `+$1E`
получает 32 за тик, и юнит проходит `32 / стоимость` клеток — то есть
стоимость 32 это клетка за тик, 99 — клетка примерно раз в три тика.
Диагональный шаг дороже на четверть (`$01A392`).

Здоровье тратят таблицы B и C, и делает это `ApplyTerrainDamage` `$01D3BA`
раз за пересмотр поведения:

| действие `+$15` | что это | таблица |
|---|---|---|
| `$0B` | ходьба | B |
| `$2F` | ходьба, не разрывая стычку | B |
| `$32` | оглушение от бедствия | B |
| `$0F` | переход в следующую клетку | C |

Юнит, которым правит игрок, от урона освобождён — но только в первых трёх
состояниях, в `$0F` освобождения нет.

Обе таблицы, B и C, лежат подряд и **обе по 22 слова**: B занимает `+$50`…
`+$7B`, C — `+$7C`…`+$A7`. Раньше здесь стояло «C — 19 слов», и три
последних столбца в неё не попадали. Проверяется двумя способами: у
улучшенной копии C начинается с `+$11A`, и `$11A + 22×2 = $146` — ровно
длина блока параметров, 326 байт; а значения по индексам 19, 20, 21
осмысленны (у типа 20 стоит `9999`, как и в таблице B, — это один из
смертельных типов).

Индекс не проверяется на длину таблицы, только на диапазон:

```asm
	cmpi.b	#$1F,d7
	beq.w	loc_01D448        ; тип 31 пропускается особо
	cmpi.b	#$16,d7
	bgt.w	loc_01D458        ; > 22 — заглушка отладчика и выход
```

Типы 23…30 — те самые, что по маске `$7F800000` загораживают обзор, то
есть стоять на них юнит не может; отказ выглядит как оставленная проверка
утверждения. А вот индекс 22 и тип 31 в таблицу не попадают: 22 читает
слово на `+$A8`, младший байт которого — `+$A9`, шанс случайного поворота.
"""
import io
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paths import rom_bytes

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

ROM = rom_bytes()
U16 = lambda o: struct.unpack_from(">H", ROM, o)[0]
U32 = lambda o: struct.unpack_from(">I", ROM, o)[0]

DESC = 0x01FC5A
SPECIES = [("1 ｽﾃｺﾞ", 0x064), ("2 ﾄﾘｹﾗ", 0x094), ("3 ｱﾛ", 0x0C4),
           ("4 ﾃｨﾗﾉ", 0x0F4), ("5 ﾌﾟﾃﾗ", 0x124), ("6 ﾋﾟｰﾁｬﾝ", 0x154)]
# таблица -> (смещение обычной, смещение улучшенной, длина, ширина элемента)
TABLES = [("A", 0x3A, 0xD8, 22, 1), ("B", 0x50, 0xEE, 22, 2),
          ("C", 0x7C, 0x11A, 22, 2)]
LETHAL = (11, 12, 13, 20)


def block(off):
    return U32(DESC + off)


def row(p, base, n, w):
    if w == 1:
        return [ROM[p + base + i] for i in range(n)]
    return [U16(p + base + 2 * i) for i in range(n)]


def table(which, elite):
    _nm, a, b, n, w = next(t for t in TABLES if t[0] == which)
    base = b if elite else a
    return {nm: row(block(off), base, n, w) for nm, off in SPECIES}


def md_table(p, data, n, title):
    p("%s\n\n" % title)
    p("| вид | " + " | ".join(str(t) for t in range(n)) + " |\n")
    p("|---" * (n + 1) + "|\n")
    for nm, _off in SPECIES:
        cells = []
        for t, v in enumerate(data[nm]):
            cells.append("**%d**" % v if t in LETHAL or v >= 999 else str(v))
        p("| %s | %s |\n" % (nm, " | ".join(cells)))
    p("\n")


def main():
    out = os.path.join(HERE, "docs", "game-terrain.md")
    f = io.open(out, "w", encoding="utf-8", newline="\n")
    p = f.write
    p("# Чего стоит шаг: скорость и урон от местности\n\n")
    p("Собрано `tools/terrain.py` (`make terrain`).\n\n")
    p("СГЕНЕРИРОВАНО — правки затираются, меняйте инструмент.\n"
      "Вывод, который надо сохранить, пишите в соседний, ручной файл.\n\n")
    p(__doc__[__doc__.index("В блоке параметров"):].strip() + "\n\n")

    p("## Обычные\n\n")
    md_table(p, table("A", False), 22,
             "### Таблица A — делитель скорости (меньше значит быстрее)")
    md_table(p, table("B", False), 22, "### Таблица B — урон при ходьбе")
    md_table(p, table("C", False), 22,
             "### Таблица C — урон при входе в клетку")

    p("## Улучшенные\n\n")
    md_table(p, table("A", True), 22, "### Таблица A")
    md_table(p, table("B", True), 22, "### Таблица B")
    md_table(p, table("C", True), 22, "### Таблица C")

    # ── что из таблиц видно ─────────────────────────────────────────────
    A, B, C = table("A", False), table("B", False), table("C", False)
    Ae, Be = table("A", True), table("B", True)
    open_t = range(0, 8)

    p("## Что из этого видно\n\n")

    p("### Травоядные платят за шаг вдесятеро больше хищников\n\n")
    p("Урон при ходьбе по открытой местности (типы 0…7), таблица B:\n\n")
    p("| вид | урон | во сколько раз от минимума |\n|---|---|---|\n")
    vals = {nm: B[nm][0] for nm, _ in SPECIES}
    lo = min(vals.values())
    for nm, _ in SPECIES:
        p("| %s | %d | ×%.0f |\n" % (nm, vals[nm], vals[nm] / lo))
    p("\nЭто и есть хозяйство игры: травоядное тратит здоровье просто тем, "
      "что ходит,\nи обязано пастись, а хищник почти не платит и обязан "
      "охотиться.\n\n")

    p("### Смертельная местность отмечена дважды\n\n")
    bad = [t for t in range(22)
           if all(A[nm][t] == 99 for nm, _ in SPECIES if nm != "5 ﾌﾟﾃﾗ")
           and all(B[nm][t] >= 9999 for nm, _ in SPECIES if nm != "5 ﾌﾟﾃﾗ")]
    p("Типы %s: в таблице A стоимость 99, в таблице B урон 9999. "
      "Две независимые\nтаблицы, заполненные разными числами, говорят одно ")

    p("### Улучшение — не только польза\n\n")
    p("Оно ускоряет и выравнивает шаг, но урон от трудной местности местами "
      "**растёт**:\n\n")
    p("| вид | тип | B обычная | B улучшенная |\n|---|---|---|---|\n")
    worse = 0
    for nm, _ in SPECIES:
        for t in range(22):
            if B[nm][t] < 9999 and Be[nm][t] > B[nm][t]:
                p("| %s | %d | %d | %d |\n" % (nm, t, B[nm][t], Be[nm][t]))
                worse += 1
    p("\nКлеток, ставших опаснее: **%d**. На открытой местности картина "
      "смешанная:\n\n" % worse)
    avg = lambda r: sum(r[t] for t in open_t) / len(list(open_t))
    p("| вид | шаг A, среднее по 0…7 | урон B, среднее по 0…7 |\n"
      "|---|---|---|\n")
    for nm, _ in SPECIES:
        p("| %s | %.1f → %.1f | %.1f → %.1f |\n"
          % (nm, avg(A[nm]), avg(Ae[nm]), avg(B[nm]), avg(Be[nm])))
    p("\nШаг на просторе ускоряется у всех, а вот урон — как когда: у ｱﾛ и "
      "ﾋﾟｰﾁｬﾝ падает\nвдвое-втрое, у ﾃｨﾗﾉ **растёт**, у ﾄﾘｹﾗ и ﾌﾟﾃﾗ не "
      "меняется. То есть усиление —\n**размен**, а не улучшение по всем осям: "
      "быстрее всегда, дешевле не всегда,\nа на тяжёлой местности чаще "
      "хрупче.\n\n")

    p("### Странности в данных\n\n")
    p("* У улучшенной ﾋﾟｰﾁｬﾝ стоимость шага на тип 13 равна %d, то есть она "
      "туда проходит,\n  но урон в таблицах B и C остался 9999. Зайти может, "
      "зайдя — гибнет.\n" % Ae["6 ﾋﾟｰﾁｬﾝ"][13])
    ce = table("C", True)
    p("* У улучшенного ｽﾃｺﾞ в таблице C на тип 11 стоит **%d**, а не 9999, "
      "как у всех\n  остальных и как у него же в таблице B. Похоже на "
      "потерянную девятку.\n" % ce["1 ｽﾃｺﾞ"][11])
    p("* Улучшенная ﾌﾟﾃﾗ проходит тип 20 за %d при уроне %d, тогда как "
      "обычная платит\n  %d и получает %d. Единственный вид, которому "
      "усиление открывает местность.\n\n"
      % (Ae["5 ﾌﾟﾃﾗ"][20], Be["5 ﾌﾟﾃﾗ"][20], A["5 ﾌﾟﾃﾗ"][20], B["5 ﾌﾟﾃﾗ"][20]))

    p("## Чего эти таблицы НЕ содержат\n\n")
    p("- Усталости. Отдельной шкалы выносливости в записи юнита нет: "
      "движение стоит\n  времени (таблица A) и здоровья (B и C), и больше "
      "ничего.\n")
    p("- Имён у большинства типов. Опознаны четыре, по ценам посадки и по\n"
      "  поведению ([game-map.md](game-map.md)): **1 — ｸｻ** (трава, 300 EN),\n"
      "  **5 — ｵﾊﾅ** (цветы, 500), **21 — ｲﾊﾞﾗ** (колючки, 700) и **24 — ｷ**\n"
      "  (дерево, 2500). Колючки растут цепочкой 21 → 22 → 23: верхние две\n"
      "  стадии непроходимы ни для кого, 23 вдобавок гасит обзор, и сбить\n"
      "  стадию умеет только ﾃｨﾗﾉ ([game-ai-rules.md](game-ai-rules.md)).\n"
      "  Дерево, наоборот, не растёт вовсе и не ломается ничем, кроме погоды.\n"
      "  Смертельные разобраны отдельно: 12 — огонь, 13 — разлом от\n"
      "  землетрясения, 11 — по поведению лава, а про 20 не известно ничего,\n"
      "  кроме того, что он убивает ([game-map.md](game-map.md)).\n")
    f.close()
    print("записано: %s" % os.path.relpath(out, HERE))
    return 0


if __name__ == "__main__":
    sys.exit(main())
